/**
 * AI 에이전트(Claude Code·Codex)용 gpl-controller MCP 등록의 순수 규칙 — vscode·파일 I/O 없음.
 *
 * 설계(2026-11-04, ai-handoff §1-GV): 등록은 **사용자 범위 한 곳**(Claude Code `~/.claude.json` 의 user scope,
 * Codex `~/.codex/config.toml`)에 둔다. 서버 경로는 확장 globalStorage 의 안정 사본이라 확장을 업데이트해도 바뀌지
 * 않고, 제어기 주소는 MCP 서버가 확장 창의 presence 에서 따오므로(controller-mcp `resolveControllerAddress`) 설정에
 * 적지 않는다. 그래서 워크스페이스마다 `.mcp.json`·CLAUDE.md 안내 블록을 만들던 종전 Export 방식은 폐기했다 —
 * IP 가 바뀌면 낡고, SVN 작업본에 개인 절대 경로가 섞였다. 안전 규칙은 MCP 서버 `instructions` 로 매 세션 전달된다.
 * 이 모듈은 그 등록의 판정·생성과, 종전 방식이 남긴 워크스페이스 파일의 정리 규칙을 담는다.
 */

export const MCP_SERVER_NAME = 'gpl-controller';
/**
 * 확장이 등록하는 MCP 의 전송 정책. 제어기는 명령 콘솔 클라이언트를 하나만 받으므로 AI 가 별도 TCP 로 폴백하면
 * 사람이 연결한 VS Code 세션과 경쟁한다. `only` 는 AI 명령을 Agent Bridge 로만 보내 확장의 단일 소켓·직렬 큐를 공유한다.
 */
export const SHARED_CONTROLLER_BRIDGE_MODE = 'only';

// 종전 Export 가 CLAUDE.md/AGENTS.md 에 넣던 자동 블록 표식 — 정리(strip) 대상을 찾는 데만 쓴다.
export const GUIDE_VERSION_MARK = '<!-- gpl-controller-mcp guide version:';
export const GUIDE_BEGIN = '<!-- BEGIN gpl-controller-mcp guide (auto-generated by "GPL: Export AI Agent Setup" — 수동 편집 금지, 재실행 시 이 블록만 교체됨) -->';
export const GUIDE_END = '<!-- END gpl-controller-mcp guide -->';
/** 종전 Export 가 CLAUDE.md 를 새로 만들 때 넣던 머리말 — 블록을 지운 뒤 이것만 남으면 파일째 지운다. */
export const LEGACY_GUIDE_FILE_HEADER = '# 이 프로젝트에서 AI가 지킬 규칙';
/** 더 이상 쓰지 않는 환경변수 — 주소는 확장 창을 따르고(§1-GV), 대상 프로젝트는 세션마다 project_target 으로 정한다. */
const OBSOLETE_ENV_KEYS = ['GPL_HOST', 'GPL_PORT', 'GPL_PROJECT', 'GPL_PROJECT_DIR'];

export interface McpServerEntry {
	type: 'stdio';
	command: string;
	args: string[];
	env: Record<string, string>;
}

/** 확장이 등록하는 항목 — 제어기 주소·프로젝트를 적지 않는다. */
export function desiredMcpEntry(serverScript: string): McpServerEntry {
	return { type: 'stdio', command: 'node', args: [serverScript], env: { GPL_BRIDGE: SHARED_CONTROLLER_BRIDGE_MODE } };
}

/**
 * - `absent`: 등록 없음
 * - `current`: 확장 사본을 가리키고 설정도 지금 규칙과 같음
 * - `outdated`: 확장 사본을 가리키지만 설정이 옛 규칙(GPL_HOST 고정·bridge 모드 등) — 확장이 고쳐 써도 되는 우리 항목
 * - `foreign`: 다른 서버 파일을 가리킴(개발 소스 등 사용자가 직접 등록) — 묻지 않고 건드리지 않는다
 * - `unreadable`: 설정 파일을 해석할 수 없음 — 손상 방지를 위해 쓰지 않는다
 */
export type RegistrationState = 'absent' | 'current' | 'outdated' | 'foreign' | 'unreadable';

export interface RegistrationReport {
	state: RegistrationState;
	/** 등록이 가리키는 서버 파일(args[0]) */
	script?: string;
	detail?: string;
}

function record(value: unknown): Record<string, unknown> | undefined {
	return value !== null && typeof value === 'object' && !Array.isArray(value)
		? value as Record<string, unknown> : undefined;
}

export function sameSetupPath(a: string, b: string): boolean {
	return normalizeDirKey(a) === normalizeDirKey(b);
}

/** 등록 항목 하나(형식 무관한 command/args/env 모양)를 판정한다. */
export function classifyEntry(entry: unknown, stableScript: string): RegistrationReport {
	const e = record(entry);
	if (!e) { return { state: 'absent' }; }
	const args = Array.isArray(e.args) ? e.args : [];
	const script = typeof args[0] === 'string' ? args[0] : undefined;
	if (!script || !sameSetupPath(script, stableScript)) {
		return { state: 'foreign', script, detail: script ? `다른 서버 파일을 가리킴: ${script}` : '서버 파일 인자(args[0])가 없음' };
	}
	const env = record(e.env) ?? {};
	const reasons: string[] = [];
	if (typeof e.command !== 'string' || !/^node(?:\.exe)?$/i.test(e.command.split(/[\\/]/).pop() ?? '')) { reasons.push('command 가 node 가 아님'); }
	if (e.type !== undefined && e.type !== 'stdio') { reasons.push('type 이 stdio 가 아님'); }
	if (args.length !== 1) { reasons.push('추가 인자가 있음'); }
	if (env.GPL_BRIDGE !== SHARED_CONTROLLER_BRIDGE_MODE) { reasons.push(`GPL_BRIDGE 가 ${SHARED_CONTROLLER_BRIDGE_MODE} 가 아님`); }
	const obsolete = OBSOLETE_ENV_KEYS.filter(key => env[key] !== undefined);
	if (obsolete.length > 0) { reasons.push(`쓰지 않는 환경변수 ${obsolete.join('/')}`); }
	return reasons.length === 0
		? { state: 'current', script }
		: { state: 'outdated', script, detail: reasons.join(', ') };
}

/** Claude Code 사용자 설정(`~/.claude.json`) 본문에서 user scope 등록을 판정한다. 파일이 없으면 `text` 는 undefined. */
export function classifyClaudeUserConfig(text: string | undefined, stableScript: string): RegistrationReport {
	if (text === undefined) { return { state: 'absent' }; }
	try {
		return classifyEntry(record(record(JSON.parse(text))?.mcpServers)?.[MCP_SERVER_NAME], stableScript);
	} catch (err) {
		return { state: 'unreadable', detail: err instanceof Error ? err.message : String(err) };
	}
}

// ── Codex config.toml ────────────────────────────────────────────────────────
// TOML 전체 파서는 두지 않는다 — 우리 테이블(`[mcp_servers.gpl-controller]` 과 그 하위 테이블)의 범위만 찾아
// 그 안의 단순 `key = value` 만 읽고, 쓸 때는 그 범위만 교체한다. 나머지 줄은 바이트 그대로 둔다.

const CODEX_TABLE_RE = /^\s*\[\s*mcp_servers\s*\.\s*(?:"gpl-controller"|'gpl-controller'|gpl-controller)\s*(?:\.\s*([^\]]+?))?\s*\]\s*(?:#.*)?$/;
const TOML_HEADER_RE = /^\s*\[/;

interface LineRange { start: number; end: number; sub?: string }

function codexRanges(lines: string[]): LineRange[] {
	const ranges: LineRange[] = [];
	for (let i = 0; i < lines.length; i++) {
		const m = CODEX_TABLE_RE.exec(lines[i]);
		if (!m) { continue; }
		let end = i + 1;
		while (end < lines.length && !TOML_HEADER_RE.test(lines[end])) { end++; }
		ranges.push({ start: i, end, sub: m[1]?.trim().replace(/^["']|["']$/g, '') });
		i = end - 1;
	}
	return ranges;
}

/** TOML 문자열 리터럴들을 순서대로 뽑는다(basic `"…"` 의 이스케이프, literal `'…'`). */
function tomlStrings(value: string): string[] {
	const out: string[] = [];
	const re = /"((?:[^"\\]|\\.)*)"|'([^']*)'/g;
	let m: RegExpExecArray | null;
	while ((m = re.exec(value)) !== null) {
		out.push(m[1] !== undefined
			? m[1].replace(/\\u([0-9a-fA-F]{4})/g, (_s, h) => String.fromCharCode(parseInt(h, 16)))
				.replace(/\\(["\\/bfnrt])/g, (_s, c: string) => ({ b: '\b', f: '\f', n: '\n', r: '\r', t: '\t' } as Record<string, string>)[c] ?? c)
			: m[2]);
	}
	return out;
}

/** 우리 테이블의 키·값을 읽어 `classifyEntry` 가 받는 모양으로 만든다. 테이블이 없으면 undefined. */
export function readCodexEntry(text: string): Record<string, unknown> | undefined {
	const lines = text.split(/\r?\n/);
	const ranges = codexRanges(lines);
	if (ranges.length === 0) { return undefined; }
	const entry: Record<string, unknown> = {};
	const env: Record<string, string> = {};
	for (const range of ranges) {
		for (let i = range.start + 1; i < range.end; i++) {
			const kv = /^\s*([A-Za-z0-9_-]+|"[^"]*")\s*=\s*(.*)$/.exec(lines[i]);
			if (!kv) { continue; }
			const key = kv[1].replace(/^"|"$/g, '');
			let value = kv[2];
			// 여러 줄 배열·인라인 테이블은 닫는 괄호까지 이어 붙인다.
			const open = value.trimStart()[0];
			const close = open === '[' ? ']' : open === '{' ? '}' : undefined;
			while (close && !value.includes(close) && i + 1 < range.end) { value += ` ${lines[++i]}`; }
			if (range.sub === 'env') {
				const s = tomlStrings(value);
				if (s.length > 0) { env[key] = s[0]; }
			} else if (!range.sub) {
				if (key === 'args') { entry.args = tomlStrings(value); }
				else if (key === 'command') { entry.command = tomlStrings(value)[0]; }
				else if (key === 'env' && open === '{') {
					const re = /([A-Za-z0-9_-]+)\s*=\s*("(?:[^"\\]|\\.)*"|'[^']*')/g;
					let m: RegExpExecArray | null;
					while ((m = re.exec(value)) !== null) { env[m[1]] = tomlStrings(m[2])[0]; }
				}
			}
		}
	}
	entry.env = env;
	return entry;
}

export function classifyCodexConfig(text: string | undefined, stableScript: string): RegistrationReport {
	if (text === undefined) { return { state: 'absent' }; }
	return classifyEntry(readCodexEntry(text), stableScript);
}

/** 백슬래시가 든 값(Windows 경로)은 이스케이프 없는 literal `'…'`, 나머지는 basic `"…"`. */
function tomlString(value: string): string {
	return value.includes('\\') && !/['\r\n]/.test(value)
		? `'${value}'`
		: `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '\\r').replace(/\n/g, '\\n')}"`;
}

/** 우리 테이블들을 지우고 그 자리(없으면 파일 끝)에 새 항목을 쓴다. 다른 줄과 줄바꿈 형식은 그대로 둔다. */
export function upsertCodexServer(text: string, entry: McpServerEntry): string {
	const eol = text.includes('\r\n') ? '\r\n' : '\n';
	const lines = text.length > 0 ? text.split(/\r?\n/) : [];
	const block = [
		`[mcp_servers.${MCP_SERVER_NAME}]`,
		`command = ${tomlString(entry.command)}`,
		`args = [${entry.args.map(tomlString).join(', ')}]`,
		'',
		`[mcp_servers.${MCP_SERVER_NAME}.env]`,
		...Object.entries(entry.env).map(([k, v]) => `${k} = ${tomlString(v)}`),
	];
	const ranges = codexRanges(lines);
	if (ranges.length === 0) {
		while (lines.length > 0 && lines[lines.length - 1].trim() === '') { lines.pop(); }
		return [...lines, ...(lines.length > 0 ? [''] : []), ...block, ''].join(eol);
	}
	const insertAt = ranges[0].start;
	const drop = new Set<number>();
	for (const r of ranges) {
		for (let i = r.start; i < r.end; i++) { drop.add(i); }
	}
	const out: string[] = [];
	for (let i = 0; i < lines.length; i++) {
		if (i === insertAt) {
			out.push(...block);
			// 다음 테이블과 빈 줄 하나로 띄운다(지운 범위의 꼬리 빈 줄을 대신한다).
			if (lines.slice(i).some((_l, k) => !drop.has(i + k))) { out.push(''); }
		}
		if (!drop.has(i)) { out.push(lines[i]); }
	}
	return out.join(eol);
}

// ── 종전 Export 가 남긴 워크스페이스 파일 정리 ───────────────────────────────

export interface StripResult {
	changed: boolean;
	/** 바뀐 본문. `null` 이면 남은 내용이 없어 파일째 지운다. */
	text: string | null;
	error?: string;
}

/** `.mcp.json` 에서 gpl-controller 항목만 지운다. 다른 서버·키는 보존하고, 아무것도 남지 않으면 파일째 지운다. */
export function stripMcpJsonEntry(text: string): StripResult {
	let config: Record<string, unknown> | undefined;
	try {
		config = record(JSON.parse(text));
	} catch (err) {
		return { changed: false, text, error: `JSON 파싱 실패 — 건드리지 않음: ${err instanceof Error ? err.message : String(err)}` };
	}
	const servers = record(config?.mcpServers);
	if (!config || !servers || !(MCP_SERVER_NAME in servers)) { return { changed: false, text }; }
	delete servers[MCP_SERVER_NAME];
	if (Object.keys(servers).length === 0) { delete config.mcpServers; }
	if (Object.keys(config).length === 0) { return { changed: true, text: null }; }
	const eol = text.includes('\r\n') ? '\r\n' : '\n';
	return { changed: true, text: JSON.stringify(config, null, 2).replace(/\n/g, eol) + eol };
}

/** CLAUDE.md/AGENTS.md 에서 자동 블록만 지운다. 사용자가 쓴 본문은 보존하고, 남는 것이 머리말뿐이면 파일째 지운다. */
export function stripGuideBlock(text: string): StripResult {
	const begin = text.indexOf(GUIDE_BEGIN);
	const end = text.indexOf(GUIDE_END);
	if (begin === -1 || end < begin) { return { changed: false, text }; }
	const eol = text.includes('\r\n') ? '\r\n' : '\n';
	const before = text.slice(0, begin).replace(/(?:\r?\n)+$/, '');
	const after = text.slice(end + GUIDE_END.length).replace(/^(?:\r?\n)+/, '');
	const rest = before && after ? `${before}${eol}${eol}${after}` : before ? `${before}${eol}` : after;
	const meaningful = rest.trim();
	if (meaningful === '' || meaningful === LEGACY_GUIDE_FILE_HEADER) { return { changed: true, text: null }; }
	return { changed: true, text: rest };
}
